// Record one native example per study, including the actual study bot's replies.
// No outcome overrides: the seeded route is graded by ordinary exercise rules.
import {Worker,isMainThread,parentPort,workerData} from 'node:worker_threads';
import {writeFile,readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {EXERCISES} from '../dist/exercise-positions.js';
import {currentTeam,RULES_VERSION} from '../dist/engine.js';
import {createExerciseSession,applyExerciseAction} from '../dist/exercise-session.js';
import {chooseExerciseAction} from '../dist/exercise-ai.js';

if(isMainThread){
  const records=new Array(EXERCISES.length);let cursor=0;
  async function slot(){while(cursor<EXERCISES.length){const index=cursor++;
    records[index]=await new Promise((resolve,reject)=>{
      let result;const worker=new Worker(new URL(import.meta.url),{workerData:{index}});
      worker.on('message',value=>{result=value;});worker.on('error',reject);
      worker.on('exit',code=>code||!result?reject(Error(`Exercise ${index+1} could not be recorded`)):resolve(result));
    });console.log(`${index+1}. ${EXERCISES[index].title}: ${records[index].actions.length} actions, solved`);
  }}
  await Promise.all(Array.from({length:4},slot));
  const engineHash=createHash('sha256').update(await readFile(new URL('../dist/engine.js',import.meta.url))).digest('hex');
  const data={format:1,rulesVersion:RULES_VERSION,engineHash,examples:Object.fromEntries(EXERCISES.map((def,i)=>[def.id,records[i]]))};
  await writeFile(new URL('../dist/exercise-solutions.js',import.meta.url),`// Generated by scripts/build-exercise-solutions.mjs. Native actions, no outcome overrides.\nexport const EXERCISE_SOLUTIONS=${JSON.stringify(data)};\n`);
}else{
  const definition=EXERCISES[workerData.index],seed=1984,actions=[];let session=createExerciseSession(definition,{seed});
  function act(action){if(actions.length>=96)throw Error('Example exceeded the study action limit');session=applyExerciseAction(session,action);actions.push(action);}
  function reply(){for(let n=0;session.status==='active'&&currentTeam(session.game)!==session.playerTeam;n++){
    if(n>=18)throw Error('Study opponent did not return control');act(chooseExerciseAction(session.game));
  }}
  for(const action of definition.exampleActions){reply();if(session.status!=='active')throw Error(`${definition.id}: example stopped before its final action`);act(action);}
  reply();if(session.status!=='solved')throw Error(`${definition.id}: ${session.feedback}`);
  parentPort.postMessage({revision:definition.revision||1,seed,actions});
}
